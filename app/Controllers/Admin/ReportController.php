<?php

namespace Emunicipal\Controllers\Admin;

use Emunicipal\Controllers\BaseController;
use Emunicipal\Middleware\AuthMiddleware;
use Emunicipal\Helpers\SessionHelper;
use Emunicipal\Models\DocumentType;
use Emunicipal\Models\AuditLog;
use Emunicipal\Services\AuditLogService;
use Emunicipal\Core\Database;
use Emunicipal\Core\Logger;

/**
 * ReportController — Admin request summary reports.
 *
 * Implements Req 12.2–12.3 (Reports section):
 *  12.2 — Filterable request summary reports: date range, document type, status
 *  12.3 — Results displayed in a paginated table within the browser
 *  12.5 — Default page size of 20 records per page
 *  13.1 — Audit log entry when a report is generated
 *
 * Routes:
 *  GET /admin/reports
 *
 * Security:
 *  - Admin-only (AuthMiddleware::requireRole('admin'))
 *  - All filter values validated / cast server-side
 *  - All SQL uses PDO prepared statements (Req 14.2)
 *  - No password_hash or sensitive fields exposed
 */
class ReportController extends BaseController
{
    private const DEFAULT_PER_PAGE = 20;

    // -------------------------------------------------------------------------
    // GET /admin/reports
    // -------------------------------------------------------------------------

    public function index(): void
    {
        AuthMiddleware::requireRole('admin');

        $adminId = AuthMiddleware::userId();

        // ── Collect and sanitise filter inputs (never trust GET params) ──────
        $filters = $this->collectFilters();

        // ── Load document types for the filter dropdown ───────────────────────
        $documentTypes = [];
        try {
            $documentTypes = (new DocumentType())->allWithRequirementCount();
        } catch (\Throwable $e) {
            Logger::error('ReportController: failed to load document types: ' . $e->getMessage());
        }

        // ── Build the paginated report query ──────────────────────────────────
        $page    = max(1, (int)($filters['page'] ?? 1));
        // Use configured records_per_page (Req 20) — fall back to constant default
        $perPage = \Emunicipal\Services\SettingsService::recordsPerPage() ?: self::DEFAULT_PER_PAGE;

        $reportRows  = [];
        $totalRows   = 0;
        $summaryStats = [];

        try {
            [$reportRows, $totalRows] = $this->fetchReportRows($filters, $page, $perPage);
            $summaryStats             = $this->fetchSummaryStats($filters);
        } catch (\Throwable $e) {
            Logger::error('ReportController: query failed: ' . $e->getMessage());
            SessionHelper::flash('error', 'Unable to generate the report. Please try again.');
        }

        $totalPages = $perPage > 0 ? (int) ceil($totalRows / $perPage) : 1;

        // ── Audit log: report generated (Req 12.3, 13.1) ─────────────────────
        // Only log when the admin actively submits a filter (not on bare page load).
        if ($filters['_submitted'] ?? false) {
            AuditLogService::log(
                $adminId, 'admin',
                AuditLog::ACTION_REPORT_GENERATED,
                'reports',
                'requests', null,
                null,
                $this->filterSnapshot($filters),
                "Report generated by admin ID {$adminId} with filters: " .
                    $this->filterSummaryText($filters)
            );
        }

        $this->renderWithLayout('admin/reports/index', [
            'title'         => 'Reports — eMunicipal',
            'activePage'    => 'reports',
            'filters'       => $filters,
            'documentTypes' => $documentTypes,
            'reportRows'    => $reportRows,
            'totalRows'     => $totalRows,
            'totalPages'    => $totalPages,
            'currentPage'   => $page,
            'perPage'       => $perPage,
            'summaryStats'  => $summaryStats,
        ], 'layouts/auth');
    }

    // -------------------------------------------------------------------------
    // Private — filter collection
    // -------------------------------------------------------------------------

    /**
     * Read, validate, and return sanitised filter values from $_GET.
     * Returns a flat array; no raw user strings are carried through untouched.
     */
    private function collectFilters(): array
    {
        $dateFrom = trim($_GET['date_from'] ?? '');
        $dateTo   = trim($_GET['date_to']   ?? '');
        $status   = trim($_GET['status']    ?? '');
        $dtId     = (int)($_GET['document_type_id'] ?? 0);
        $page     = max(1, (int)($_GET['page'] ?? 1));

        // Validate date format YYYY-MM-DD
        if ($dateFrom !== '' && !$this->isValidDate($dateFrom)) {
            $dateFrom = '';
        }
        if ($dateTo !== '' && !$this->isValidDate($dateTo)) {
            $dateTo = '';
        }
        // Clamp: date_from cannot be after date_to
        if ($dateFrom !== '' && $dateTo !== '' && $dateFrom > $dateTo) {
            [$dateFrom, $dateTo] = [$dateTo, $dateFrom];
        }

        // Whitelist status values
        $validStatuses = [
            'pending', 'under_verification', 'additional_info_required',
            'approved', 'rejected', 'ready_for_claiming', 'completed', 'cancelled',
        ];
        if (!in_array($status, $validStatuses, true)) {
            $status = '';
        }

        // document_type_id must be a positive integer
        if ($dtId < 0) $dtId = 0;

        // Track whether the form was submitted (used to decide when to audit log)
        $submitted = isset($_GET['date_from']) || isset($_GET['date_to'])
            || isset($_GET['status']) || isset($_GET['document_type_id']);

        return [
            'date_from'        => $dateFrom,
            'date_to'          => $dateTo,
            'status'           => $status,
            'document_type_id' => $dtId,
            'page'             => $page,
            '_submitted'       => $submitted,
        ];
    }

    // -------------------------------------------------------------------------
    // Private — queries
    // -------------------------------------------------------------------------

    /**
     * Return [rows, total] for the paginated report table.
     * All WHERE conditions use bound parameters (Req 14.2).
     */
    private function fetchReportRows(array $filters, int $page, int $perPage): array
    {
        $db     = Database::getInstance();
        $where  = ['1=1'];
        $params = [];

        if ($filters['date_from'] !== '') {
            $where[]              = 'DATE(r.created_at) >= :date_from';
            $params[':date_from'] = $filters['date_from'];
        }
        if ($filters['date_to'] !== '') {
            $where[]            = 'DATE(r.created_at) <= :date_to';
            $params[':date_to'] = $filters['date_to'];
        }
        if ($filters['status'] !== '') {
            $where[]           = 'r.status = :status';
            $params[':status'] = $filters['status'];
        }
        if ($filters['document_type_id'] > 0) {
            $where[]          = 'r.document_type_id = :dt_id';
            $params[':dt_id'] = $filters['document_type_id'];
        }

        $whereStr = implode(' AND ', $where);

        // COUNT
        $countStmt = $db->prepare(
            "SELECT COUNT(*) FROM requests r WHERE {$whereStr}"
        );
        $countStmt->execute($params);
        $total = (int)$countStmt->fetchColumn();

        // DATA
        $offset = ($page - 1) * $perPage;
        $params[':lim'] = $perPage;
        $params[':off'] = $offset;

        $stmt = $db->prepare(
            "SELECT
                 r.id,
                 r.reference_number,
                 r.status,
                 r.copies_requested,
                 r.created_at,
                 r.updated_at,
                 u.first_name,
                 u.last_name,
                 u.email,
                 dt.name  AS document_type_name,
                 dt.processing_fee
             FROM requests r
             JOIN users u           ON r.user_id          = u.id
             JOIN document_types dt ON r.document_type_id = dt.id
             WHERE {$whereStr}
             ORDER BY r.created_at DESC
             LIMIT :lim OFFSET :off"
        );

        foreach ($params as $key => $value) {
            $stmt->bindValue(
                $key, $value,
                in_array($key, [':lim', ':off'], true) ? \PDO::PARAM_INT : \PDO::PARAM_STR
            );
        }
        $stmt->execute();
        $rows = $stmt->fetchAll();

        return [$rows, $total];
    }

    /**
     * Return aggregate summary stats for the current filter set.
     * Used to display totals at the top of the report page.
     */
    private function fetchSummaryStats(array $filters): array
    {
        $db     = Database::getInstance();
        $where  = ['1=1'];
        $params = [];

        if ($filters['date_from'] !== '') {
            $where[]              = 'DATE(r.created_at) >= :date_from';
            $params[':date_from'] = $filters['date_from'];
        }
        if ($filters['date_to'] !== '') {
            $where[]            = 'DATE(r.created_at) <= :date_to';
            $params[':date_to'] = $filters['date_to'];
        }
        if ($filters['status'] !== '') {
            $where[]           = 'r.status = :status';
            $params[':status'] = $filters['status'];
        }
        if ($filters['document_type_id'] > 0) {
            $where[]          = 'r.document_type_id = :dt_id';
            $params[':dt_id'] = $filters['document_type_id'];
        }

        $whereStr = implode(' AND ', $where);

        // Total matching requests
        $totalStmt = $db->prepare("SELECT COUNT(*) FROM requests r WHERE {$whereStr}");
        $totalStmt->execute($params);
        $total = (int)$totalStmt->fetchColumn();

        // By status
        $byStatusStmt = $db->prepare(
            "SELECT r.status, COUNT(*) AS cnt
             FROM requests r
             WHERE {$whereStr}
             GROUP BY r.status
             ORDER BY cnt DESC"
        );
        $byStatusStmt->execute($params);
        $byStatus = [];
        foreach ($byStatusStmt->fetchAll() as $row) {
            $byStatus[$row['status']] = (int)$row['cnt'];
        }

        // By document type (top 5)
        $byDocStmt = $db->prepare(
            "SELECT dt.name AS doc_type, COUNT(*) AS cnt
             FROM requests r
             JOIN document_types dt ON r.document_type_id = dt.id
             WHERE {$whereStr}
             GROUP BY r.document_type_id, dt.name
             ORDER BY cnt DESC
             LIMIT 5"
        );
        $byDocStmt->execute($params);
        $byDoc = $byDocStmt->fetchAll();

        return [
            'total'     => $total,
            'by_status' => $byStatus,
            'by_doc'    => $byDoc,
        ];
    }

    // -------------------------------------------------------------------------
    // Private — helpers
    // -------------------------------------------------------------------------

    private function isValidDate(string $date): bool
    {
        if (!preg_match('/^\d{4}-\d{2}-\d{2}$/', $date)) return false;
        [$y, $m, $d] = explode('-', $date);
        return checkdate((int)$m, (int)$d, (int)$y);
    }

    /** Build a safe snapshot of filter values for the audit log new_value field. */
    private function filterSnapshot(array $filters): array
    {
        return array_filter([
            'date_from'        => $filters['date_from']        ?: null,
            'date_to'          => $filters['date_to']          ?: null,
            'status'           => $filters['status']           ?: null,
            'document_type_id' => $filters['document_type_id'] ?: null,
        ]);
    }

    /** Human-readable summary for the audit log description. */
    private function filterSummaryText(array $filters): string
    {
        $parts = [];
        if ($filters['date_from'])        $parts[] = "from={$filters['date_from']}";
        if ($filters['date_to'])          $parts[] = "to={$filters['date_to']}";
        if ($filters['status'])           $parts[] = "status={$filters['status']}";
        if ($filters['document_type_id']) $parts[] = "doc_type_id={$filters['document_type_id']}";
        return $parts ? implode(', ', $parts) : 'none (all records)';
    }
}
